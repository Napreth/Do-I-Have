param(
    [string]$Sdk = $env:ANDROID_HOME,
    [string]$Platform = 'android-37.0'
)
$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path $PSScriptRoot -Parent
$jar = Join-Path $Sdk "platforms/$Platform/android.jar"
$source = Join-Path $Sdk "sources/$Platform/android/app/AppOpsManager.java"
$javap = Join-Path $env:JAVA_HOME 'bin/javap.exe'
$declarations = & $javap -classpath $jar -constants 'android.Manifest$permission'
$permissions = @{}
foreach ($line in $declarations) {
    if ($line -match 'String (\w+) = "([^"]+)"') { $permissions[$Matches[1]] = $Matches[2] }
}
if ($permissions.Count -lt 100) { throw 'Could not read the public SDK permission constants.' }
# USE_EXACT_ALARM bypasses the user-controlled SCHEDULE_EXACT_ALARM flow.
# Keep the complete operation catalog, but isolate this grant test in the manifest.
$declaredPermissions = $permissions.Values | Where-Object { $_ -ne 'android.permission.USE_EXACT_ALARM' } | Sort-Object -Unique
$uses = ($declaredPermissions | ForEach-Object { "    <uses-permission android:name=`"$_`" />" }) -join "`n"
$manifest = @"
<?xml version="1.0" encoding="utf-8"?>
<!-- Public permission catalog generated by scripts/generate-platform-data.ps1.
     Broad and protected permissions are intentional in this permission inspection tool;
     declaring them does not grant them. Only runtime request APIs and supported
     special-access settings actions appear in the permission list. -->
<manifest xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:tools="http://schemas.android.com/tools"
    tools:ignore="ProtectedPermissions,QueryAllPackagesPermission,ScopedStorage,HighSamplingRate">
$uses
    <uses-feature android:name="android.hardware.camera" android:required="false" />
    <uses-feature android:name="android.hardware.camera.autofocus" android:required="false" />
    <uses-feature android:name="android.hardware.microphone" android:required="false" />
    <uses-feature android:name="android.hardware.telephony" android:required="false" />
    <uses-feature android:name="android.hardware.location" android:required="false" />
    <uses-feature android:name="android.hardware.bluetooth" android:required="false" />
    <application android:label="@string/app_name" android:icon="@mipmap/ic_launcher"
        android:theme="@style/AppTheme" android:allowBackup="false" android:fullBackupContent="false"
        android:dataExtractionRules="@xml/data_extraction_rules" android:supportsRtl="true">
        <activity android:name=".MainActivity" android:exported="true" android:windowSoftInputMode="adjustResize">
            <intent-filter>
                <action android:name="android.intent.action.MAIN" />
                <category android:name="android.intent.category.LAUNCHER" />
            </intent-filter>
        </activity>
    </application>
</manifest>
"@
[IO.File]::WriteAllText((Join-Path $projectRoot 'app/src/main/AndroidManifest.xml'), $manifest)

# AppOpInfo's array index is the AOSP operation number. This avoids hidden-API reflection.
$text = Get-Content -Raw -LiteralPath $source
$strings = @{}
foreach ($match in [regex]::Matches($text, 'String\s+(OPSTR_\w+)\s*=\s*"([^"]+)"')) {
    $strings[$match.Groups[1].Value] = $match.Groups[2].Value
}
$table = $text.Substring($text.IndexOf('static final AppOpInfo[] sAppOpInfos'))
$table = $table.Substring(0, $table.IndexOf("`n    };"))
$entries = [regex]::Matches($table, 'new AppOpInfo.Builder\(\s*(OP_\w+),\s*(OPSTR_\w+|""),\s*"([^"]*)"[^)]*\)([\s\S]*?)(?=new AppOpInfo.Builder|$)')
$expected = [int]([regex]::Match($text, '_NUM_OP\s*=\s*(\d+)').Groups[1].Value)
if ($entries.Count -ne $expected) { throw "Expected $expected operations; parsed $($entries.Count)." }
$lines = [Collections.Generic.List[string]]::new()
$lines.Add('# AOSP Android 17 / API 37.0. Generated from SDK AppOpsManager.java. Apache-2.0; see NOTICE.')
for ($i = 0; $i -lt $entries.Count; $i++) {
    $entry = $entries[$i]
    if ($entry.Groups[1].Value -eq 'OP_NONE') { continue }
    $name = $strings[$entry.Groups[2].Value]
    if (-not $name) { throw "Missing operation string: $($entry.Groups[2].Value)" }
    $permission = ''
    $permissionMatch = [regex]::Match($entry.Groups[4].Value, '\.setPermission\((?:android\.)?Manifest.permission.(\w+)\)')
    if ($permissionMatch.Success) {
        $key = $permissionMatch.Groups[1].Value
        $permission = $permissions[$key]
        if (-not $permission) { $permission = "android.permission.$key" }
    }
    $lines.Add("$i`t$name`t$permission")
}
if ($lines[27] -notmatch '^26\s+android:camera\s') { throw 'Camera operation number sanity check failed.' }
$assets = Join-Path $projectRoot 'app/src/main/assets'
New-Item -ItemType Directory -Force $assets | Out-Null
[IO.File]::WriteAllLines((Join-Path $assets 'appops.tsv'), $lines)
Copy-Item -LiteralPath (Join-Path $projectRoot 'LICENSE'), (Join-Path $projectRoot 'NOTICE') -Destination $assets
Write-Host "Generated $($declaredPermissions.Count) declared permissions and $($entries.Count) AOSP AppOps slots."
